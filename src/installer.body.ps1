#Requires -Version 5.1
<#
=============================================================================
 Install-ProfilePerf -- one-line installer
 Version: @@VERSION@@

 Speeds up an interactive PowerShell startup that uses the Chris Titus Tech
 (CTT) profile, by deferring slow module imports until first use and probing
 the installed editor first.

 INSTALL (from the internet):
     irm @@INSTALL_URL@@ | iex

 INSTALL (from a local copy):
     .\install.ps1

 CHECK STATUS:
     .\Install-ProfilePerf.ps1 -Check
       or, without saving anything to disk:
     & ([scriptblock]::Create((irm @@INSTALL_URL@@))) -Check

 UNINSTALL:
     .\Install-ProfilePerf.ps1 -Uninstall
       or:
     & ([scriptblock]::Create((irm @@INSTALL_URL@@))) -Uninstall

 This file is generated by build/Build.ps1 from src/. Edit the sources, not
 this file. The payload scripts are embedded below as base64 so that the whole
 installer stays a single self-contained script that works when piped to
 Invoke-Expression, where $PSScriptRoot is not available.
=============================================================================
#>
[CmdletBinding(SupportsShouldProcess, ConfirmImpact = 'Medium')]
param(
    [ValidateSet('Install', 'Uninstall', 'Check')]
    [string]$Action = 'Install',

    # Profile that receives the fixes. Defaults to the current user's profile.
    [string]$ProfilePath = $PROFILE.CurrentUserCurrentHost,

    # Profile.ps1 (AllHosts) that hosts the startup reminder. It is deliberately a
    # different file from the one above, because Update-Profile only overwrites the
    # CurrentUserCurrentHost profile, and the reminder must survive that.
    [string]$AllHostsPath = $PROFILE.CurrentUserAllHosts,

    # Where the payload scripts are installed.
    [string]$InstallDir,

    [switch]$Uninstall,
    [switch]$Check,
    [switch]$Force,
    [switch]$SkipGuard
)

$ErrorActionPreference = 'Stop'

# Alternate spellings, so the flag-style invocation works too.
if ($Uninstall) { $Action = 'Uninstall' }
if ($Check) { $Action = 'Check' }

# When piped to Invoke-Expression there is no way to pass parameters, so allow the
# action to arrive through the environment as well.
if (-not $PSBoundParameters.ContainsKey('Action') -and $env:LKS_PP_ACTION) {
    $Action = $env:LKS_PP_ACTION
}
if (-not $PSBoundParameters.ContainsKey('ProfilePath') -and $env:LKS_PP_PROFILE) {
    $ProfilePath = $env:LKS_PP_PROFILE
}

# ---------------------------------------------------------------------------
# Embedded payloads (base64 of UTF-8). Base64 cannot contain a line starting with
# the here-string terminator, so this embedding is safe -- unlike pasting the
# scripts in verbatim, which would break because they contain such lines.
# ---------------------------------------------------------------------------

$repairScriptB64 = @'
@@PAYLOAD_REPAIR_B64@@
'@

$guardScriptB64 = @'
@@PAYLOAD_GUARD_B64@@
'@

$uninstallerScriptB64 = @'
@@PAYLOAD_UNINSTALLER_B64@@
'@

$Version = '@@VERSION@@'
$InstallUrl = '@@INSTALL_URL@@'

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

function Write-Head {
    param([string]$Text)
    Write-Host ''
    Write-Host $Text -ForegroundColor Cyan
}

function Write-Ok    { param([string]$T) Write-Host "  $T" -ForegroundColor Green }
function Write-Note  { param([string]$T) Write-Host "  $T" -ForegroundColor DarkGray }
function Write-Warn2 { param([string]$T) Write-Host "  $T" -ForegroundColor Yellow }
function Write-Bad   { param([string]$T) Write-Host "  $T" -ForegroundColor Red }

function Get-PayloadText {
    param([string]$B64)
    [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String(($B64 -replace '\s', '')))
}

function Get-DefaultInstallDir {
    # $HOME is more reliable than $env:USERPROFILE around profile loading, but fall
    # back rather than fail.
    $base = if ($HOME) { $HOME } elseif ($env:USERPROFILE) { $env:USERPROFILE } else { $env:LOCALAPPDATA }
    Join-Path $base '.pwsh-profile-perf'
}

function Get-Eol {
    param([string]$Text)
    $crlf = ([regex]::Matches($Text, "`r`n")).Count
    $lf = ([regex]::Matches($Text, "(?<!`r)`n")).Count
    if ($crlf -gt $lf) { "`r`n" } else { "`n" }
}

function Write-TextFileLf {
    # Preserve the target file's line endings; write UTF-8 without BOM, which is how
    # PowerShell profiles are normally stored.
    param([string]$Path, [string]$Text, [string]$Eol = "`n")

    $out = if ($Eol -eq "`r`n") { $Text.Replace("`n", "`r`n") } else { $Text }
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($Path, $out, $utf8NoBom)
}

function Test-ProfileShape {
    <#
    .SYNOPSIS
        Sanity-checks that the target looks like a profile this tool understands.
    #>
    param([string]$Text)

    # Either it is already patched, or it still contains stock CTT code we recognise.
    $markers = @('LKS-PERF-TI-BEGIN', 'LKS-PERF-CHOCO-BEGIN', 'LKS-PERF-EDITOR-BEGIN', 'LKS-PERF-LAZY-BEGIN')
    foreach ($m in $markers) {
        if ($Text.Contains("# >>> $m")) { return $true }
    }
    $stock = @(
        'if (Get-Module -ListAvailable -Name Terminal-Icons) {',
        "foreach (`$candidate in 'nvim', 'pvim', 'vim', 'vi', 'code', 'codium', 'notepad++', 'sublime_text') {",
        'Invoke-ScheduledProfileUpdate'
    )
    foreach ($s in $stock) {
        if ($Text.Contains($s)) { return $true }
    }
    return $false
}

function Get-GuardSpan {
    <#
    .SYNOPSIS
        Locates the guard block in the AllHosts profile, including the decorative
        banner line of '# ===...' immediately before and/or after it.

    .DESCRIPTION
        Working from the markers rather than from the exact installed text means a
        reinstall or upgrade replaces the old block cleanly even if it was written by
        an earlier version of this tool. Returns $null when the block is absent.

        The span deliberately includes the blank line that follows the block. Install
        writes '<guard text><eol>' in place of the span, so if the span stopped at the
        banner line the blank line after it would survive and a second install would add
        another one -- the file would grow by a newline on every reinstall.
    #>
    param([string]$Text)

    $beginMarker = '# >>> LKS-PERF-GUARD-BEGIN'
    $endMarker = '# <<< LKS-PERF-GUARD-END'

    $beginIdx = $Text.IndexOf($beginMarker, [StringComparison]::Ordinal)
    if ($beginIdx -lt 0) { return $null }
    $endIdx = $Text.IndexOf($endMarker, $beginIdx, [StringComparison]::Ordinal)
    if ($endIdx -lt 0) { return $null }

    # Full lines, so removal leaves no stray blank lines behind.
    $start = $Text.LastIndexOf("`n", [Math]::Max(0, $beginIdx - 1))
    $start = if ($start -lt 0) { 0 } else { $start + 1 }
    $endLine = $Text.IndexOf("`n", $endIdx)
    $end = if ($endLine -lt 0) { $Text.Length } else { $endLine + 1 }

    # Walk outwards over adjacent banner lines.
    $bannerRe = [regex]'^#\s*=+\s*$'
    $lines = $Text.Substring(0, $start) -split "`n"

    $backLines = 0
    for ($i = $lines.Count - 2; $i -ge 0; $i--) {
        if ($bannerRe.IsMatch($lines[$i])) { $backLines++ } else { break }
    }
    if ($backLines -gt 0) {
        # Recompute start as the first banner line consumed.
        $keep = $lines.Count - 1 - $backLines
        $start = ($lines[0..([Math]::Max(0, $keep - 1))] -join "`n").Length
        if ($keep -gt 0) { $start += 1 }
    }

    $fwd = $Text.Substring($end) -split "`n"
    $fwdLines = 0
    foreach ($l in $fwd) {
        if ($bannerRe.IsMatch($l)) { $fwdLines++ } else { break }
    }
    if ($fwdLines -gt 0) {
        $consumed = ($fwd[0..($fwdLines - 1)] -join "`n")
        $end = $end + $consumed.Length
        # Include the newline that follows the last banner line, if any.
        if ($end -lt $Text.Length -and $Text[$end] -eq "`n") { $end++ }
    }

    # Consume a single trailing blank line, so the span covers the separator install
    # adds after the block and reinstalls stay byte-stable.
    if ($end -lt $Text.Length -and $Text[$end] -eq "`n") { $end++ }

    [pscustomobject]@{ Start = $start; End = $end; Text = $Text.Substring($start, $end - $start) }
}

function Install-Guard {
    param([string]$Path, [string]$GuardText, [switch]$WhatIfOnly)

    $dir = Split-Path -Parent $Path
    if ($dir -and -not (Test-Path -LiteralPath $dir)) {
        New-Item -ItemType Directory -Path $dir -Force | Out-Null
    }

    $existing = if (Test-Path -LiteralPath $Path -PathType Leaf) {
        Get-Content -LiteralPath $Path -Raw
    } else {
        ''
    }
    $eol = Get-Eol $existing

    if ($existing) {
        $span = Get-GuardSpan -Text $existing
        if ($span) {
            # The span already covers the newline that terminated the last guard line
            # and the blank line after it, so inserting the guard text with a single
            # trailing newline keeps the file byte-stable across reinstalls.
            $new = $existing.Remove($span.Start, $span.End - $span.Start).Insert($span.Start, ($GuardText + $eol))
            $verb = 'updated'

            # Never leave the file unterminated.
            if (-not $new.EndsWith($eol)) { $new += $eol }
        } else {
            $sep = if ($existing.EndsWith("`n")) { '' } else { $eol }
            $new = $existing + $sep + $eol + $GuardText + $eol
            $verb = 'added'
        }
    } else {
        $new = $GuardText + $eol
        $verb = 'created'
    }

    # Validate before writing: this file runs at every shell start.
    $errors = $null
    [void][System.Management.Automation.Language.Parser]::ParseInput($new, [ref]$null, [ref]$errors)
    if ($errors -and $errors.Count -gt 0) {
        Write-Bad "guard block would break $Path; not written (line $($errors[0].Extent.StartLineNumber): $($errors[0].Message))"
        return $false
    }

    if ($WhatIfOnly) { return $true }

    Write-TextFileLf -Path $Path -Text $new -Eol $eol
    Write-Ok "$verb startup reminder in $(Split-Path -Leaf $Path)"
    return $true
}

function Uninstall-Guard {
    param([string]$Path)

    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        Write-Note 'startup reminder: no AllHosts profile, nothing to remove'
        return
    }

    $text = Get-Content -LiteralPath $Path -Raw
    $span = Get-GuardSpan -Text $text
    if (-not $span) {
        Write-Note 'startup reminder: not present'
        return
    }

    $new = $text.Remove($span.Start, $span.End - $span.Start)

    # Tidy up a file left with trailing blank lines.
    if ($new.Trim().Length -eq 0) {
        $new = ''
    } else {
        $new = $new.TrimEnd("`n", "`r") + (Get-Eol $text)
    }

    Write-TextFileLf -Path $Path -Text $new -Eol (Get-Eol $text)
    Write-Ok "removed startup reminder from $(Split-Path -Leaf $Path)"
}

# ---------------------------------------------------------------------------
# Entry
# ---------------------------------------------------------------------------

if (-not $InstallDir) { $InstallDir = Get-DefaultInstallDir }

$repairFile = Join-Path $InstallDir 'Repair-ProfilePerf.ps1'
$guardFile = Join-Path $InstallDir 'Guard.ps1'
$uninstallerFile = Join-Path $InstallDir 'Uninstall-ProfilePerf.ps1'
$manifestFile = Join-Path $InstallDir 'ProfilePerf.json'

$isPwsh = $PSVersionTable.PSEdition -eq 'Core'
$editionName = if ($isPwsh) { 'PowerShell 7+' } else { "Windows PowerShell $($PSVersionTable.PSVersion)" }

Write-Head 'Profile startup-performance fixes'
Write-Note "host    : $editionName"
Write-Note "version : $Version"
Write-Note "profile : $ProfilePath"
Write-Note "install : $InstallDir"

# ===========================================================================
if ($Action -eq 'Check') {

    $repairText = Get-PayloadText $repairScriptB64
    $tmp = Join-Path ([IO.Path]::GetTempPath()) "ppcheck-$([Guid]::NewGuid().ToString('n')).ps1"
    Write-TextFileLf -Path $tmp -Text $repairText -Eol "`n"
    try {
        & (if ($isPwsh) { 'pwsh.exe' } else { 'powershell.exe' }) -NoProfile -ExecutionPolicy Bypass -File $tmp -ProfilePath $ProfilePath -Check
    } finally {
        Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue
    }

    Write-Host ''
    Write-Host 'Installed files:' -ForegroundColor Cyan
    foreach ($f in $repairFile, $guardFile, $uninstallerFile, $manifestFile) {
        if (Test-Path -LiteralPath $f -PathType Leaf) {
            Write-Ok "$(Split-Path -Leaf $f)"
        } else {
            Write-Warn2 "$(Split-Path -Leaf $f) is missing"
        }
    }

    if (Test-Path -LiteralPath $AllHostsPath -PathType Leaf) {
        $hasGuard = (Get-Content -LiteralPath $AllHostsPath -Raw).Contains('# >>> LKS-PERF-GUARD-BEGIN')
        if ($hasGuard) {
            Write-Ok "startup reminder in $(Split-Path -Leaf $AllHostsPath)"
        } else {
            Write-Warn2 "startup reminder not installed in $(Split-Path -Leaf $AllHostsPath)"
        }
    }
    Write-Host ''
    return
}

# ===========================================================================
if ($Action -eq 'Uninstall') {

    $repairText = Get-PayloadText $repairScriptB64
    $tmp = Join-Path ([IO.Path]::GetTempPath()) "ppuninst-$([Guid]::NewGuid().ToString('n')).ps1"
    Write-TextFileLf -Path $tmp -Text $repairText -Eol "`n"
    try {
        & (if ($isPwsh) { 'pwsh.exe' } else { 'powershell.exe' }) -NoProfile -ExecutionPolicy Bypass -File $tmp -ProfilePath $ProfilePath -Uninstall -Confirm:$false
    } finally {
        Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue
    }

    Uninstall-Guard -Path $AllHostsPath

    if (Test-Path -LiteralPath $InstallDir) {
        Remove-Item -LiteralPath $InstallDir -Recurse -Force -ErrorAction SilentlyContinue
        if (Test-Path -LiteralPath $InstallDir) {
            Write-Warn2 "could not fully remove $InstallDir"
        } else {
            Write-Ok "removed $InstallDir"
        }
    }

    Write-Head 'Uninstalled'
    Write-Note 'Your profile has been reverted to the stock code.'
    Write-Note 'Restart the shell to use it.'
    Write-Host ''
    return
}

# ===========================================================================
# Apply

Write-Head 'Installing'

# 1. Guard the target file first: refuse to touch something that is not the
#    profile this tool understands, unless -Force says otherwise.
if (-not (Test-Path -LiteralPath $ProfilePath -PathType Leaf)) {
    Write-Bad "profile not found: $ProfilePath"
    Write-Note 'Point at yours with:  -ProfilePath "C:\path\to\Microsoft.PowerShell_profile.ps1"'
    return
}

$profileText = Get-Content -LiteralPath $ProfilePath -Raw
if (-not (Test-ProfileShape -Text $profileText) -and -not $Force) {
    Write-Bad 'this profile does not look like a profile these fixes apply to.'
    Write-Note 'Nothing was changed. These fixes target the Chris Titus Tech profile layout.'
    Write-Note 'If you are sure, re-run with -Force. Note that even with -Force the fixes'
    Write-Note 'can only be applied where the expected stock code exists, so a profile that'
    Write-Note 'does not derive from the CTT profile will still be left alone at the patch step.'
    return
}

# 2. Write the payload scripts.
if (-not $PSCmdlet.ShouldProcess($InstallDir, 'Write payload scripts')) { return }

$installDirParent = Split-Path -Parent $InstallDir
if ($installDirParent -and -not (Test-Path -LiteralPath $installDirParent)) {
    New-Item -ItemType Directory -Path $installDirParent -Force | Out-Null
}
if (-not (Test-Path -LiteralPath $InstallDir)) {
    New-Item -ItemType Directory -Path $InstallDir -Force | Out-Null
}

$repairText = Get-PayloadText $repairScriptB64
$guardTextTemplate = Get-PayloadText $guardScriptB64

# The guard needs to know where the repair script lives. Bake the resolved path in
# so the guard works regardless of how it is loaded.
$guardText = $guardTextTemplate.Replace('@@INSTALL_DIR@@', $InstallDir)

Write-TextFileLf -Path $repairFile -Text $repairText -Eol "`n"
Write-Ok "installed $(Split-Path -Leaf $repairFile)"
Write-TextFileLf -Path $guardFile -Text $guardText -Eol "`n"
Write-Ok "installed $(Split-Path -Leaf $guardFile)"

# Save a standalone uninstaller with the resolved paths baked in, so it works with no
# arguments and no network access. This is preferred over copying this installer to
# disk, because a piped irm|iex script has no reliable text of itself to re-save.
$uninstallerText = Get-PayloadText $uninstallerScriptB64
$uninstallerText = $uninstallerText.Replace('@@INSTALL_DIR@@', $InstallDir)
$uninstallerText = $uninstallerText.Replace('@@PROFILE_PATH@@', $ProfilePath)
$uninstallerText = $uninstallerText.Replace('@@ALLHOSTS_PATH@@', $AllHostsPath)
Write-TextFileLf -Path $uninstallerFile -Text $uninstallerText -Eol "`n"
Write-Ok "installed $(Split-Path -Leaf $uninstallerFile)"

$manifest = [ordered]@{
    version     = $Version
    installedAt = (Get-Date).ToString('s')
    installUrl  = $InstallUrl
    installDir  = $InstallDir
    profilePath = $ProfilePath
    allHostsPath = $AllHostsPath
    host        = $editionName
    regions     = @('TI', 'CHOCO', 'EDITOR', 'LAZY', 'NOUPDATE')
    guardMarker = 'LKS-PERF-GUARD'
}
($manifest | ConvertTo-Json -Depth 4) | Set-Content -LiteralPath $manifestFile -Encoding utf8
Write-Ok "installed $(Split-Path -Leaf $manifestFile)"

# 3. Patch the main profile by running the installed repair script.
Write-Host ''
Write-Host 'Applying profile fixes:' -ForegroundColor Cyan
$shell = if ($isPwsh) { 'pwsh.exe' } else { 'powershell.exe' }
& $shell -NoProfile -ExecutionPolicy Bypass -File $repairFile -ProfilePath $ProfilePath -Confirm:$false

# 4. Install the startup reminder into the AllHosts profile.
if (-not $SkipGuard) {
    Write-Host ''
    Write-Host 'Startup reminder:' -ForegroundColor Cyan
    [void](Install-Guard -Path $AllHostsPath -GuardText $guardText)
}

# 5. Verify.
Write-Host ''
Write-Host 'Verify:' -ForegroundColor Cyan
$after = Get-Content -LiteralPath $ProfilePath -Raw
$present = 0
foreach ($r in 'TI', 'CHOCO', 'EDITOR', 'LAZY', 'NOUPDATE') {
    if ($after.Contains("# >>> LKS-PERF-$r-BEGIN")) { $present++ }
}
if ($present -eq 5) {
    Write-Ok "all 5 fixes present in $(Split-Path -Leaf $ProfilePath)"
} else {
    Write-Warn2 "$present of 5 fixes present"
}

$errors = $null
[void][System.Management.Automation.Language.Parser]::ParseFile($ProfilePath, [ref]$null, [ref]$errors)
if ($errors -and $errors.Count -gt 0) {
    Write-Bad "profile has $($errors.Count) syntax error(s):"
    foreach ($e in $errors) { Write-Bad "  line $($e.Extent.StartLineNumber): $($e.Message)" }
} else {
    Write-Ok 'profile parses cleanly'
}

Write-Head 'Installed'
Write-Note 'Open a NEW terminal to see the faster startup.'
Write-Note ''
Write-Note 'Commands (available in new shells):'
Write-Note '  Repair-ProfilePerf            re-apply fixes after a profile update'
Write-Note '  Repair-ProfilePerf -Check     report status'
Write-Note '  Get-ProfilePerfStatus         show each region'
Write-Note '  Disable-ProfilePerfNotice     hide the startup line'
Write-Note ''
Write-Note 'Uninstall:'
Write-Note "  & `"$uninstallerFile`" -Uninstall"
Write-Host ''
